const DICTIONARIES: Record<Language, Record<MessageKey, string>> = {
  ja,
  en,
};

export function resolveLanguage(preference: 'ja' | 'en' | 'auto'): Language {
  if (preference !== 'auto') return preference;
  if (typeof navigator === 'undefined') return 'ja';
  return navigator.language.toLowerCase().startsWith('en') ? 'en' : 'ja';
}

export function translate(
  language: Language,
  key: MessageKey,
  params?: Record<string, string | number>,
): string {
  const template = DICTIONARIES[language][key] ?? DICTIONARIES.ja[key] ?? key;
  if (params === undefined) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in params ? String(params[name]) : match,
  );
}

